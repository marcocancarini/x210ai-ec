from cpu8051 import CPU
def run(prog,**k):
    c=CPU(bytes(prog)+bytes(0x20000-len(prog)))
    c.sfr[0x81]=0x40
    n=0
    while c.code(c.pc)!=0xA5:
        c.step(); n+=1; assert n<9999
    return c
# ADD/flags, ADDC, SUBB, DA, MUL, DIV, SWAP, RLC, RRC, XCH, XCHD, CJNE, DJNZ, MOVC, stack, bits, indirect upper iRAM, banks
